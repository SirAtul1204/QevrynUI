import { build } from 'esbuild';
import { mkdir, writeFile, readFile, readdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { root, pluginRoot, catalog } from './generate.mjs';
await mkdir(resolve(pluginRoot, 'server'), { recursive: true });
const result = await build({ absWorkingDir: root, entryPoints: [resolve(root, 'packages/mcp/src/server.ts')], outfile: resolve(pluginRoot, 'server/index.mjs'), bundle: true, platform: 'node', format: 'esm', target: 'node22', minify: true, legalComments: 'eof', metafile: true, banner: { js: '// Generated by @qevryn/mcp. Do not edit.\nimport { createRequire } from "node:module"; const require = createRequire(import.meta.url);' } });
const licenses = new Map();
for (const output of Object.values(result.metafile.outputs)) for (const [input, contribution] of Object.entries(output.inputs)) {
  if (!contribution.bytesInOutput || !input.includes('node_modules')) continue;
  let directory = dirname(resolve(root, input));
  while (directory !== dirname(directory)) {
    let metadata;
    try { metadata = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8')); } catch { directory = dirname(directory); continue; }
    if (!metadata.name || !metadata.version) { directory = dirname(directory); continue; }
    const key = `${metadata.name}@${metadata.version}`;
    if (!licenses.has(key)) {
      const files = await readdir(directory);
      const licenseFiles = files.filter(name => /^(license|licence|notice)(\.|$)/i.test(name));
      if (!licenseFiles.length) throw new Error(`Missing bundled dependency license: ${key}`);
      licenses.set(key, `## ${key} (${metadata.license ?? 'see license'})\n\n` + (await Promise.all(licenseFiles.map(name => readFile(resolve(directory, name), 'utf8')))).join('\n'));
    }
    break;
  }
}
await writeFile(resolve(pluginRoot, 'THIRD_PARTY_LICENSES.txt'), [...licenses.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, text]) => text).join('\n\n'));
await writeFile(resolve(pluginRoot, 'LICENSE'), await readFile(resolve(root, 'LICENSE')));
// Keep the portable manifest, compatibility overlay, and server version aligned.
const portable = JSON.parse(await readFile(resolve(pluginRoot, 'plugin.json'), 'utf8'));
if (portable.version !== catalog.pluginVersion) throw new Error('Plugin/server version mismatch');
await mkdir(resolve(pluginRoot, '.codex-plugin'), { recursive: true });
const { extensions, $schema, ...metadata } = portable;
await writeFile(resolve(pluginRoot, '.codex-plugin/plugin.json'), JSON.stringify({ ...metadata, interface: extensions['com.openai'].interface, skills: './skills', mcpServers: './.mcp.json' }, null, 2) + '\n');
await writeFile(resolve(pluginRoot, '.mcp.json'), JSON.stringify({ mcpServers: { qevryn: { command: 'node', args: ['${PLUGIN_ROOT}/server/index.mjs'] } } }, null, 2) + '\n');
await mkdir(resolve(root, 'packages/mcp/dist'), { recursive: true });
await writeFile(resolve(root, 'packages/mcp/dist/build.json'), JSON.stringify({ uiVersion: catalog.uiVersion, exports: catalog.components.length, recipes: catalog.recipes.length }) + '\n');
console.error(`Built Qevryn plugin: ${catalog.components.length} exports, ${catalog.recipes.length} recipes, UI ${catalog.uiVersion}.`);
